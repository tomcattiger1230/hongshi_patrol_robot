def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gui", action="store_true", help="Show the Isaac Sim window.")
    parser.add_argument(
        "--demo",
        action="store_true",
        help="Drive a repeating forward-and-turn pattern.",
    )
    parser.add_argument(
        "--test-seconds",
        type=float,
        default=0.0,
        help="Stop automatically after this many simulated seconds.",
    )
    parser.add_argument("--cmd-vel-topic", default="/cmd_vel")
    parser.add_argument(
        "--command-timeout",
        type=float,
        default=0.6,
        help="Brake if cmd_vel is silent for this many wall-clock seconds.",
    )
    parser.add_argument("--odom-topic", default="/odom")
    parser.add_argument(
        "--realtime-factor",
        type=float,
        default=1.0,
        help="Maximum simulated seconds per wall second; use 0 for unthrottled.",
    )
    parser.add_argument(
        "--urdf-path",
        type=Path,
        required=True,
        help="Expanded URDF generated by the ROS environment.",
    )
    args, kit_args = parser.parse_known_args()
    # SimulationApp forwards sys.argv to Kit. Remove this script's options so
    # Kit does not interpret --test-seconds as its own shutdown timer.
    sys.argv = [sys.argv[0], *kit_args]
    return args


