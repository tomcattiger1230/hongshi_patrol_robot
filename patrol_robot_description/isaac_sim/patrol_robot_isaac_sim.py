def _import_robot(urdf_path: Path, output_dir: Path) -> Path:
    config = URDFImporterConfig(
        urdf_path=str(urdf_path),
        usd_path=str(output_dir),
        merge_fixed_joints=True,
        fix_base=False,
        joint_drive_type="force",
        joint_target_type={
            "front_left_steering_joint": "position",
            "front_right_steering_joint": "position",
            "front_left_wheel_joint": "none",
            "front_right_wheel_joint": "none",
            "rear_left_wheel_joint": "velocity",
            "rear_right_wheel_joint": "velocity",
        },
        override_joint_stiffness={
            "front_left_steering_joint": 5000.0,
            "front_right_steering_joint": 5000.0,
            "front_left_wheel_joint": 0.0,
            "front_right_wheel_joint": 0.0,
            "rear_left_wheel_joint": 0.0,
            "rear_right_wheel_joint": 0.0,
        },
        override_joint_damping={
            "front_left_steering_joint": 200.0,
            "front_right_steering_joint": 200.0,
            # A target type of "none" must have no drive gains.  Leaving a
            # small damping here creates a zero-velocity drive on the passive
            # front wheels and makes their ground contacts chatter.
            "front_left_wheel_joint": 0.0,
            "front_right_wheel_joint": 0.0,
            # Velocity-drive damping acts as the rear motor's proportional
            # torque gain. A value of 10 cannot move the 100+ kg articulation
            # reliably and mostly lets the tire contacts chatter in place.
            "rear_left_wheel_joint": 100.0,
            "rear_right_wheel_joint": 100.0,
        },
        # convert_joints_attributes() runs after apply_joint_drives() and
        # replaces these per-joint gains with the raw URDF dynamics values.
        # Keep it disabled and author the required PhysX limits explicitly
        # after the articulation tensor view has been initialized.
        run_multi_physics_conversion=False,
        run_asset_transformer=False,
    )
    usd_path = URDFImporter(config).import_urdf()
    if not usd_path:
        raise RuntimeError("Isaac Sim URDF importer did not return a USD path")
    return Path(usd_path)


def _add_static_box(
    stage,
    path: str,
    size: tuple[float, float, float],
    position: tuple[float, float, float],
    color: tuple[float, float, float],
    yaw: float = 0.0,
) -> None:
    cube = UsdGeom.Cube.Define(stage, path)
    cube.GetSizeAttr().Set(1.0)
    cube.GetDisplayColorAttr().Set([Gf.Vec3f(*color)])
    xform = UsdGeom.Xformable(cube)
    xform.AddTranslateOp().Set(Gf.Vec3d(*position))
    if yaw:
        xform.AddRotateZOp().Set(math.degrees(yaw))
    xform.AddScaleOp().Set(Gf.Vec3f(*size))
    UsdPhysics.CollisionAPI.Apply(cube.GetPrim())


def _add_static_cylinder(
    stage,
    path: str,
    radius: float,
    height: float,
    position: tuple[float, float, float],
    color: tuple[float, float, float],
) -> None:
    cylinder = UsdGeom.Cylinder.Define(stage, path)
    cylinder.CreateRadiusAttr(radius)
    cylinder.CreateHeightAttr(height)
    cylinder.CreateAxisAttr("Z")
    cylinder.GetDisplayColorAttr().Set([Gf.Vec3f(*color)])
    UsdGeom.Xformable(cylinder).AddTranslateOp().Set(Gf.Vec3d(*position))
    UsdPhysics.CollisionAPI.Apply(cylinder.GetPrim())


def _configure_wheel_colliders(stage) -> None:
    """Replace faceted cylinder contacts with stable Isaac wheel contacts.

    PhysX cooks URDF cylinders as convex geometry.  A heavy chassis resting on
    those facets can continually tip between contact points.  NVIDIA's sample
    Ackermann asset likewise uses a bounding-sphere approximation for wheels.
    Keep the cylinder visuals, but use analytic spheres for Isaac collisions.
    """
    for imported_path, sphere_path in zip(
        IMPORTED_WHEEL_COLLIDER_PATHS,
        ISAAC_WHEEL_COLLIDER_PATHS,
        strict=True,
    ):
        imported_prim = stage.GetPrimAtPath(imported_path)
        if not imported_prim.IsValid():
            raise RuntimeError(f"Imported wheel collider not found: {imported_path}")
        UsdPhysics.CollisionAPI(imported_prim).CreateCollisionEnabledAttr(False)

        sphere = UsdGeom.Sphere.Define(stage, sphere_path)
        sphere.CreateRadiusAttr(WHEEL_RADIUS)
        sphere.CreateVisibilityAttr(UsdGeom.Tokens.invisible)
        UsdPhysics.CollisionAPI.Apply(sphere.GetPrim())


def _bind_tire_physics_material(stage) -> None:
    """Apply deterministic rubber contact properties to wheels and ground."""
    material = UsdShade.Material.Define(stage, "/World/PhysicsMaterials/Tire")
    material_api = UsdPhysics.MaterialAPI.Apply(material.GetPrim())
    material_api.CreateStaticFrictionAttr(TIRE_STATIC_FRICTION)
    material_api.CreateDynamicFrictionAttr(TIRE_DYNAMIC_FRICTION)
    # A heavy, unsuspended AGV tire must not bounce on initial contact.
    material_api.CreateRestitutionAttr(0.0)

    for path in ["/World/Ground", *ISAAC_WHEEL_COLLIDER_PATHS]:
        prim = stage.GetPrimAtPath(path)
        if not prim.IsValid():
            raise RuntimeError(f"Physics collider not found for material binding: {path}")
        UsdShade.MaterialBindingAPI.Apply(prim).Bind(
            material,
            bindingStrength=UsdShade.Tokens.strongerThanDescendants,
            materialPurpose="physics",
        )


