def _create_mid360s_lidar() -> LidarSensor:
    """Create an RTX lidar with a MID-360-like range and ROS 2 output."""
    # Use a complete local 360-degree, 32-channel rotary profile. Creating an
    # unconfigured OmniLidar uses schema defaults whose rays occupy only one
    # sector; SLAM then tries to rotate the map to match that asymmetric scan.
    # Hesai_XT32_SD10 ships inside Isaac Sim, so this remains fully offline.
    staging_path = "/World/mid360s_lidar"
    lidar_path = f"{ISAAC_BASE_LINK_PATH}/mid360s_lidar"
    omni.kit.commands.execute(
        "IsaacSensorCreateRtxLidar",
        # The legacy creator resolves its built-in config only at a root path.
        # Move the fully configured prim under the dynamic chassis afterwards.
        path=staging_path,
        parent=None,
        config="Hesai_XT32_SD10",
        translation=Gf.Vec3d(*MID360_POSITION),
        orientation=Gf.Quatd(1.0, 0.0, 0.0, 0.0),
    )
    omni.kit.commands.execute(
        "MovePrim",
        path_from=staging_path,
        path_to=lidar_path,
    )
    lidar_prim = stage_utils.get_current_stage().GetPrimAtPath(lidar_path)
    if not lidar_prim.IsValid():
        raise RuntimeError(f"Failed to attach RTX lidar at {lidar_path}")
    lidar = Lidar(
        str(lidar_prim.GetPath()),
        tick_rate=10.0,
        aux_output_level="FULL",
        # Re-author a chassis-local pose after changing the USD namespace.
        # Otherwise the staging transform may be interpreted in world space.
        translations=MID360_POSITION.reshape(1, 3),
        orientations=np.array([[1.0, 0.0, 0.0, 0.0]]),
        attributes={
            "omni:sensor:Core:nearRangeM": 0.10,
            "omni:sensor:Core:farRangeM": 70.0,
            "omni:sensor:Core:outputFrameOfReference": "SENSOR",
        },
    )
    sensor = LidarSensor(lidar, annotators=[])
    sensor.attach_writer(
        "RtxLidarROS2PublishPointCloud",
        topicName="livox/lidar",
        frameId="lidar_link",
    )
    return sensor


def _bicycle_command(
    linear_x: float, angular_z: float
) -> tuple[float, float, float]:
    """Convert cmd_vel to a bounded bicycle steering angle and realized yaw rate."""
    linear_x = float(np.clip(linear_x, -MAX_LINEAR_SPEED, MAX_LINEAR_SPEED))
    if abs(linear_x) < 1e-4:
        return 0.0, 0.0, 0.0
    steering_angle = math.atan(WHEEL_BASE * angular_z / linear_x)
    steering_angle = float(
        np.clip(steering_angle, -MAX_STEERING_ANGLE, MAX_STEERING_ANGLE)
    )
    realized_angular_z = linear_x * math.tan(steering_angle) / WHEEL_BASE
    return linear_x, steering_angle, realized_angular_z


def _stamp(seconds: float):
    whole_seconds = int(seconds)
    nanoseconds = int((seconds - whole_seconds) * 1e9)
    return whole_seconds, nanoseconds


class IsaacRosInterface(Node):
    """Translate ROS 2 velocity commands and publish Isaac Sim state."""

    def __init__(self) -> None:
        super().__init__("patrol_robot_isaac_sim")
        self.linear_x = 0.0
        self.angular_z = 0.0
        self._last_command_monotonic_ns = 0
        self._odom_origin_xy: np.ndarray | None = None
        self.create_subscription(
            Twist, ARGS.cmd_vel_topic, self._on_twist, 10
        )
        self._odom = self.create_publisher(Odometry, ARGS.odom_topic, 10)
        self._joint_states = self.create_publisher(JointState, "/joint_states", 10)
        self._tf = self.create_publisher(TFMessage, "/tf", 10)
        self._clock_publisher = self.create_publisher(Clock, "/clock", 10)

    def _on_twist(self, message: Twist) -> None:
        self.linear_x = float(message.linear.x)
        self.angular_z = float(message.angular.z)
        self._last_command_monotonic_ns = time.monotonic_ns()

    def demo_command(self, simulation_time: float) -> tuple[float, float]:
        phase = simulation_time % 14.55
        if phase < 4.0:
            return 0.35, 0.0
        return 0.35, 0.149

    def command(self, simulation_time: float) -> tuple[float, float]:
        if ARGS.demo and self._last_command_monotonic_ns == 0:
            return self.demo_command(simulation_time)
        if (
            self._last_command_monotonic_ns
            and time.monotonic_ns() - self._last_command_monotonic_ns
            > int(ARGS.command_timeout * 1e9)
        ):
            self.linear_x = 0.0
            self.angular_z = 0.0
        return self.linear_x, self.angular_z

    def publish_state(
        self,
        simulation_time: float,
        position: np.ndarray,
        orientation_wxyz: np.ndarray,
        joint_positions: np.ndarray,
        linear_x: float,
        angular_z: float,
    ) -> None:
        sec, nanosec = _stamp(simulation_time)
        if self._odom_origin_xy is None:
            self._odom_origin_xy = np.asarray(position[:2], dtype=float).copy()
        odom_xy = np.asarray(position[:2], dtype=float) - self._odom_origin_xy

        clock = Clock()
        clock.clock.sec = sec
        clock.clock.nanosec = nanosec
        self._clock_publisher.publish(clock)

        odom = Odometry()
        odom.header.stamp = clock.clock
        odom.header.frame_id = "odom"
        odom.child_frame_id = "base_footprint"
        # Odom is local to the spawn pose, matching Gazebo and the convention
        # expected by saved-map localization.
        odom.pose.pose.position.x = float(odom_xy[0])
        odom.pose.pose.position.y = float(odom_xy[1])
        odom.pose.pose.position.z = 0.0
        odom.pose.pose.orientation.w = float(orientation_wxyz[0])
        odom.pose.pose.orientation.x = float(orientation_wxyz[1])
        odom.pose.pose.orientation.y = float(orientation_wxyz[2])
        odom.pose.pose.orientation.z = float(orientation_wxyz[3])
        odom.twist.twist.linear.x = linear_x
        odom.twist.twist.angular.z = angular_z
        self._odom.publish(odom)

        joint_state = JointState()
        joint_state.header.stamp = clock.clock
        joint_state.name = JOINT_STATE_NAMES
        joint_state.position = [float(value) for value in joint_positions]
        self._joint_states.publish(joint_state)

        transform = TransformStamped()
        transform.header = odom.header
        transform.child_frame_id = odom.child_frame_id
        transform.transform.translation.x = odom.pose.pose.position.x
        transform.transform.translation.y = odom.pose.pose.position.y
        transform.transform.translation.z = odom.pose.pose.position.z
        transform.transform.rotation = odom.pose.pose.orientation
        self._tf.publish(TFMessage(transforms=[transform]))


def main() -> None:
    stop_requested = False

    def request_stop(_signum, _frame) -> None:
        nonlocal stop_requested
        stop_requested = True

    signal.signal(signal.SIGINT, request_stop)
    signal.signal(signal.SIGTERM, request_stop)

    temporary_dir = tempfile.TemporaryDirectory(prefix="patrol_robot_isaac_")
    ros_node = None
    try:
        app_utils.enable_extension("isaacsim.ros2.bridge")
        app_utils.enable_extension("isaacsim.sensors.rtx")
        app_utils.enable_extension("isaacsim.sensors.rtx.nodes")
        app_utils.update_app(steps=2)

        work_dir = Path(temporary_dir.name)
        robot_usd = _import_robot(ARGS.urdf_path, work_dir)
        robot = _build_scene(robot_usd)
        lidar_sensor = _create_mid360s_lidar()
        controller = AckermannController(
            wheel_base=WHEEL_BASE,
            track_width=TRACK_WIDTH,
            front_wheel_radius=WHEEL_RADIUS,
            back_wheel_radius=WHEEL_RADIUS,
            max_wheel_velocity=MAX_LINEAR_SPEED / WHEEL_RADIUS,
            max_wheel_rotation_angle=MAX_STEERING_ANGLE,
            max_acceleration=2.0,
            max_steering_angle_velocity=math.radians(25.0),
        )

        # Give the four cylindrical wheel contacts additional velocity-solver
        # iterations. The imported articulation root does not carry the PhysX
        # tuning schema by default, so apply it before authoring the setting.
        PhysxSchema.PhysxArticulationAPI.Apply(robot.prims[0])
        robot.set_solver_iteration_counts([32], [4])

        SimulationManager.setup_simulation(dt=PHYSICS_DT, device="cpu")
        physics_scene = SimulationManager.get_physics_scenes()[0]
        physics_scene.set_enabled_gpu_dynamics(False)
        app_utils.play()
        app_utils.update_app(steps=10)
        steering_dof_indices = (
            robot.get_dof_indices(STEERING_DOF_NAMES).numpy().tolist()
        )
        joint_state_dof_indices = (
            robot.get_dof_indices(JOINT_STATE_NAMES).numpy().tolist()
        )

        rclpy.init(signal_handler_options=SignalHandlerOptions.NO)
        ros_node = IsaacRosInterface()
        simulation_time = 0.0
        wall_start = time.monotonic()
        publish_every = 3
        step = 0
        last_steering_targets: np.ndarray | None = None
        last_wheel_targets: np.ndarray | None = None
        parking_position: np.ndarray | None = None
        parking_orientation: np.ndarray | None = None
        print(
            "PATROL_ISAAC_READY "
            f"cmd_vel={ARGS.cmd_vel_topic} odom={ARGS.odom_topic} "
            "lidar=/livox/lidar",
            flush=True,
        )

        while not stop_requested and (not ARGS.gui or SIMULATION_APP.is_running()):
            SIMULATION_APP.update()
            rclpy.spin_once(ros_node, timeout_sec=0.0)
            requested_linear_x, requested_angular_z = ros_node.command(
                simulation_time
            )
            linear_x, steering_angle, angular_z = _bicycle_command(
                requested_linear_x, requested_angular_z
            )
            steering_positions, wheel_velocities = controller.forward(
                [steering_angle, math.radians(25.0), linear_x, 2.0, PHYSICS_DT]
            )
            steering_targets = np.asarray(steering_positions, dtype=np.float32)
            wheel_targets = np.asarray(wheel_velocities[2:], dtype=np.float32)
            # Re-authoring identical drive targets every physics tick wakes the
            # articulation and prevents PhysX from settling at rest.  Targets
            # persist in the drives, so only update them when they change.
            moving = abs(linear_x) >= 1.0e-4
            if (
                moving
                or last_steering_targets is None
                or not np.allclose(
                    steering_targets, last_steering_targets, atol=1.0e-5
                )
            ):
                robot.set_dof_position_targets(
                    steering_targets,
                    dof_indices=steering_dof_indices,
                )
                last_steering_targets = steering_targets.copy()
            if (
                moving
                or last_wheel_targets is None
                or not np.allclose(
                    wheel_targets, last_wheel_targets, atol=1.0e-5
                )
            ):
                robot.apply_wheel_actions(wheel_targets)
                last_wheel_targets = wheel_targets.copy()

            if abs(linear_x) < 1.0e-4:
                # A real 180 kg AGV engages its brake at zero command.  Hold a
                # planar pose here as the simulation equivalent: otherwise the
                # four cylindrical wheel contacts can continually exchange
                # tiny impulses and make the free-base articulation shake.
                if parking_position is None or parking_orientation is None:
                    parked_positions, parked_orientations = robot.get_world_poses()
                    parking_position = parked_positions.numpy()[0]
                    parking_position[2] = 0.0
                    quaternion = parked_orientations.numpy()[0]
                    yaw = math.atan2(
                        2.0
                        * (
                            quaternion[0] * quaternion[3]
                            + quaternion[1] * quaternion[2]
                        ),
                        1.0
                        - 2.0
                        * (
                            quaternion[2] * quaternion[2]
                            + quaternion[3] * quaternion[3]
                        ),
                    )
                    parking_orientation = np.array(
                        [math.cos(yaw / 2.0), 0.0, 0.0, math.sin(yaw / 2.0)],
                        dtype=np.float32,
                    )
                robot.set_velocities(
                    np.zeros((1, 3), dtype=np.float32),
                    np.zeros((1, 3), dtype=np.float32),
                )
                robot.set_world_poses(
                    parking_position.reshape(1, 3),
                    parking_orientation.reshape(1, 4),
                )
            else:
                parking_position = None
                parking_orientation = None

            if step % publish_every == 0:
                positions, orientations = robot.get_world_poses()
                joint_positions = robot.get_dof_positions(
                    dof_indices=joint_state_dof_indices
                )
                ros_node.publish_state(
                    simulation_time,
                    positions.numpy()[0],
                    orientations.numpy()[0],
                    joint_positions.numpy().reshape(-1),
                    linear_x,
                    angular_z,
                )

            simulation_time += PHYSICS_DT
            step += 1
            if ARGS.realtime_factor > 0.0:
                wall_deadline = wall_start + simulation_time / ARGS.realtime_factor
                wall_delay = wall_deadline - time.monotonic()
                if wall_delay > 0.0:
                    time.sleep(wall_delay)
            if ARGS.test_seconds > 0.0 and simulation_time >= ARGS.test_seconds:
                break

        robot.apply_wheel_actions(np.zeros(2, dtype=np.float32))
        robot.set_dof_position_targets(
            np.zeros(2, dtype=np.float32),
            dof_indices=steering_dof_indices,
        )
        lidar_sensor.detach_writer("RtxLidarROS2PublishPointCloud")
        positions, _ = robot.get_world_poses()
        final_position = positions.numpy()[0]
        print(
            "PATROL_ISAAC_FINAL "
            f"x={final_position[0]:.3f} y={final_position[1]:.3f} "
            f"z={final_position[2]:.3f}",
            flush=True,
        )
    except BaseException:
        print("PATROL_ISAAC_ERROR", flush=True)
        traceback.print_exc()
        raise
    finally:
        if ros_node is not None:
            ros_node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
        app_utils.stop()
        temporary_dir.cleanup()
        SIMULATION_APP.close()


if __name__ == "__main__":
    main()
